//! `.project.json`: what it contains and how it's read.
//!
//! The rules are in docs/specs/project-metadata.md, sections 1 and 2.

use serde::de::value::MapAccessDeserializer;
use serde::de::{MapAccess, Visitor};
use serde::{Deserialize, Deserializer};
use std::fmt;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Implements `Deserialize` for a struct so that it only accepts a JSON object.
///
/// The derived `Deserialize` will also take a JSON array and fill the fields by position, which
/// the schema doesn't allow. The struct derives `Deserialize` with `#[serde(remote = "Self")]`,
/// which turns the derived code into an inherent `deserialize` function. The impl generated here
/// asks for a map and hands it to that function, so defaults and renames still work as usual.
macro_rules! deserialize_from_object {
    ($type:ident, $expecting:literal) => {
        impl<'de> Deserialize<'de> for $type {
            fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                struct ObjectVisitor;

                impl<'de> Visitor<'de> for ObjectVisitor {
                    type Value = $type;

                    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                        formatter.write_str($expecting)
                    }

                    fn visit_map<A: MapAccess<'de>>(self, map: A) -> Result<$type, A::Error> {
                        // The inherent function generated by `remote = "Self"`.
                        $type::deserialize(MapAccessDeserializer::new(map))
                    }
                }

                deserializer.deserialize_map(ObjectVisitor)
            }
        }
    };
}

/// The contents of `.project.json`: the properties in KerML 1.0 Table 12, as the normative schema
/// (`KerML-Model-Interchange.json`, `$defs/Project`) defines them.
///
/// It's the project's identity and the other projects it uses. It says nothing about the model
/// elements in the project's files.
///
/// Reading only checks JSON structure and types. Properties the schema doesn't define are
/// accepted and ignored for now.
#[derive(Debug, Deserialize)]
#[serde(remote = "Self")]
pub struct ProjectManifest {
    pub name: String,
    #[serde(default, deserialize_with = "non_null")]
    pub description: Option<String>,
    pub version: String,
    #[serde(default, deserialize_with = "non_null")]
    pub license: Option<String>,
    #[serde(default)]
    pub maintainer: Vec<String>,
    #[serde(default, deserialize_with = "non_null")]
    pub website: Option<String>,
    #[serde(default)]
    pub topic: Vec<String>,
    #[serde(default)]
    pub usage: Vec<ProjectUsage>,
}

deserialize_from_object!(ProjectManifest, "a project manifest (a JSON object)");

/// One entry in `usage`: another project this one uses, identified by its `resource` IRI.
///
/// This is a dependency between projects, not a SysML or KerML usage element in a model.
#[derive(Debug, Deserialize)]
#[serde(remote = "Self")]
pub struct ProjectUsage {
    pub resource: String,
    #[serde(default, rename = "versionConstraint", deserialize_with = "non_null")]
    pub version_constraint: Option<String>,
}

deserialize_from_object!(ProjectUsage, "a project usage (a JSON object)");

/// Reads an optional property that, when present, must be a `T`.
///
/// Serde would read `null` as `None`, but the schema gives these properties a type such as
/// `string`, so `null` is wrong. This only runs when the property is there; with
/// `#[serde(default)]` a missing one is still `None`.
fn non_null<'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error>
where
    D: Deserializer<'de>,
    T: Deserialize<'de>,
{
    T::deserialize(deserializer).map(Some)
}

/// A project manifest couldn't be read.
///
/// The message names the manifest. The cause is in [`std::error::Error::source`] and isn't
/// repeated in the message.
#[derive(Debug, thiserror::Error)]
pub enum ReadManifestError {
    #[error("cannot read project manifest {}", path.display())]
    Io { path: PathBuf, source: io::Error },
    #[error("invalid project manifest {}", path.display())]
    Parse {
        path: PathBuf,
        source: serde_json::Error,
    },
}

/// Reads a project manifest.
///
/// A symbolic link, or anything else that isn't a regular file, is an I/O error. The same property
/// twice in one object is a parse error, which the derive takes care of.
pub fn read_manifest(path: &Path) -> Result<ProjectManifest, ReadManifestError> {
    let contents = read_regular_file(path).map_err(|source| ReadManifestError::Io {
        path: path.to_path_buf(),
        source,
    })?;
    serde_json::from_str(&contents).map_err(|source| ReadManifestError::Parse {
        path: path.to_path_buf(),
        source,
    })
}

/// Reads a file, refusing symbolic links, pipes and anything else that isn't a regular file.
///
/// The check and the read are separate steps. This guards against what's in a project, not
/// against another process swapping the file in between.
fn read_regular_file(path: &Path) -> io::Result<String> {
    if fs::symlink_metadata(path)?.file_type().is_file() {
        fs::read_to_string(path)
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "not a regular file",
        ))
    }
}
