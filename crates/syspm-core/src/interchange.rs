//! `.project.json` and `.meta.json`: what they contain and how they're read.
//!
//! The rules are in docs/specs/project-metadata.md, sections 1 and 2. Properties the schema
//! doesn't define are kept as docs/specs/package-identity.md section 8 says.

use serde::de::value::MapAccessDeserializer;
use serde::de::{self, MapAccess, Visitor};
use serde::{Deserialize, Deserializer};
use std::collections::BTreeMap;
use std::collections::btree_map::Entry;
use std::fmt;
use std::fs;
use std::io;
use std::marker::PhantomData;
use std::path::{Path, PathBuf};

pub(crate) const PROJECT_MANIFEST: &str = ".project.json";
pub(crate) const PROJECT_METADATA: &str = ".meta.json";

/// Implements `Deserialize` for a struct so that it only accepts a JSON object.
///
/// The derived `Deserialize` will also take a JSON array and fill the fields by position, which
/// the schema doesn't allow. The struct derives `Deserialize` with `#[serde(remote = "Self")]`,
/// which turns the derived code into an inherent `deserialize` function. The impl generated here
/// asks for a map and hands it to that function, so defaults and renames still work as usual.
macro_rules! deserialize_from_object {
    ($type:ident, $expecting:literal) => {
        impl<'de> Deserialize<'de> for $type {
            fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                struct ObjectVisitor;

                impl<'de> Visitor<'de> for ObjectVisitor {
                    type Value = $type;

                    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                        formatter.write_str($expecting)
                    }

                    fn visit_map<A: MapAccess<'de>>(self, map: A) -> Result<$type, A::Error> {
                        // The inherent function generated by `remote = "Self"`.
                        $type::deserialize(MapAccessDeserializer::new(map))
                    }
                }

                deserializer.deserialize_map(ObjectVisitor)
            }
        }
    };
}

/// The contents of `.project.json`: the properties in KerML 1.0 Table 12, as the normative schema
/// (`KerML-Model-Interchange.json`, `$defs/Project`) defines them.
///
/// It's the project's identity and the other projects it uses. It says nothing about the model
/// elements in the project's files.
///
/// Reading only checks JSON structure and types. Properties the schema doesn't define are kept in
/// `additional_properties`.
#[derive(Debug, Deserialize)]
#[serde(remote = "Self")]
pub struct ProjectManifest {
    pub name: String,
    #[serde(default, deserialize_with = "non_null")]
    pub description: Option<String>,
    pub version: String,
    #[serde(default, deserialize_with = "non_null")]
    pub license: Option<String>,
    #[serde(default)]
    pub maintainer: Vec<String>,
    #[serde(default, deserialize_with = "non_null")]
    pub website: Option<String>,
    #[serde(default)]
    pub topic: Vec<String>,
    #[serde(default)]
    pub usage: Vec<ProjectUsage>,
    /// Properties the schema doesn't define. See [`AdditionalProperties`].
    #[serde(flatten, deserialize_with = "additional_properties")]
    pub additional_properties: AdditionalProperties,
}

deserialize_from_object!(ProjectManifest, "a project manifest (a JSON object)");

/// One entry in `usage`: another project this one uses, identified by its `resource` IRI.
///
/// This is a dependency between projects, not a SysML or KerML usage element in a model.
#[derive(Debug, Deserialize)]
#[serde(remote = "Self")]
pub struct ProjectUsage {
    pub resource: String,
    #[serde(default, rename = "versionConstraint", deserialize_with = "non_null")]
    pub version_constraint: Option<String>,
    /// Properties the schema doesn't define. See [`AdditionalProperties`].
    #[serde(flatten, deserialize_with = "additional_properties")]
    pub additional_properties: AdditionalProperties,
}

deserialize_from_object!(ProjectUsage, "a project usage (a JSON object)");

/// The contents of `.meta.json`: the properties in KerML 1.0 Table 13, as the normative schema
/// (`KerML-Model-Interchange.json`, `$defs/Meta`) defines them.
///
/// Reading only checks JSON structure and types. Properties the schema doesn't define are kept in
/// `additional_properties`. The maps are sorted by key, so they iterate in the same order whatever
/// the order in the file.
#[derive(Debug, Deserialize)]
#[serde(remote = "Self")]
pub struct ProjectMetadata {
    /// Maps the name of each top-level element in the project's root namespaces to the model
    /// file that holds it. Short names count as names. Paths are relative to the project root
    /// and use `/`.
    #[serde(deserialize_with = "unique_keys")]
    pub index: BTreeMap<String, String>,
    /// When this file was created, not when the project was. Validation checks that it's an
    /// RFC 3339 `date-time`.
    pub created: String,
    #[serde(default, deserialize_with = "non_null")]
    pub metamodel: Option<String>,
    #[serde(default, rename = "includesDerived", deserialize_with = "non_null")]
    pub includes_derived: Option<bool>,
    #[serde(default, rename = "includesImplied", deserialize_with = "non_null")]
    pub includes_implied: Option<bool>,
    /// Maps model file paths to their checksums. One checksum per file, as the schema has it,
    /// not a list as the text of Table 13 says.
    #[serde(default, deserialize_with = "unique_keys")]
    pub checksum: BTreeMap<String, Checksum>,
    /// Properties the schema doesn't define. See [`AdditionalProperties`].
    #[serde(flatten, deserialize_with = "additional_properties")]
    pub additional_properties: AdditionalProperties,
}

deserialize_from_object!(ProjectMetadata, "project metadata (a JSON object)");

/// The checksum of one model file.
#[derive(Debug, Deserialize)]
#[serde(remote = "Self")]
pub struct Checksum {
    pub value: String,
    pub algorithm: String,
    /// Properties the schema doesn't define. See [`AdditionalProperties`].
    #[serde(flatten, deserialize_with = "additional_properties")]
    pub additional_properties: AdditionalProperties,
}

deserialize_from_object!(Checksum, "a checksum (a JSON object)");

/// The properties of an object that the schema doesn't define, by name.
///
/// The schema allows them, so other tools may write them. They're kept so that syspm can report
/// them. A name that appears twice in any object they contain, at any depth, is a parse error.
///
/// These values aren't a lossless copy of the file, so never write a file back from them:
///
/// - Entries, and the members of nested objects, are sorted by name. The order in the file is
///   lost.
/// - A number is kept as a 64-bit integer or a double. An integer outside the 64-bit range, or a
///   decimal more precise than a double, comes back as a nearby double.
///
/// The first command that rewrites a standard file has to choose a lossless representation
/// (docs/specs/package-identity.md section 8).
pub type AdditionalProperties = BTreeMap<String, serde_json::Value>;

/// Reads the properties the schema doesn't define, and rejects a name that appears twice in any
/// object they contain.
fn additional_properties<'de, D>(deserializer: D) -> Result<AdditionalProperties, D::Error>
where
    D: Deserializer<'de>,
{
    let entries = unique_keys::<D, UniqueKeysValue>(deserializer)?;
    Ok(entries
        .into_iter()
        .map(|(key, UniqueKeysValue(value))| (key, value))
        .collect())
}

/// A JSON value with no repeated name in any of its objects, at any depth.
///
/// `serde_json::Value` keeps the last of two equal names, so a nested object could mean one thing
/// to one reader and something else to another. This builds the same value but rejects the
/// repeated name.
struct UniqueKeysValue(serde_json::Value);

impl<'de> Deserialize<'de> for UniqueKeysValue {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        use serde_json::{Map, Number, Value};

        struct ValueVisitor;

        impl<'de> Visitor<'de> for ValueVisitor {
            type Value = UniqueKeysValue;

            fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str("any JSON value")
            }

            fn visit_bool<E>(self, value: bool) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::Bool(value)))
            }

            fn visit_i64<E>(self, value: i64) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::Number(value.into())))
            }

            fn visit_u64<E>(self, value: u64) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::Number(value.into())))
            }

            fn visit_f64<E>(self, value: f64) -> Result<Self::Value, E> {
                // JSON has no NaN or infinity, so a parser never gives this a value that fails.
                Ok(UniqueKeysValue(
                    Number::from_f64(value).map_or(Value::Null, Value::Number),
                ))
            }

            fn visit_str<E>(self, value: &str) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::String(value.to_owned())))
            }

            fn visit_string<E>(self, value: String) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::String(value)))
            }

            fn visit_unit<E>(self) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::Null))
            }

            fn visit_none<E>(self) -> Result<Self::Value, E> {
                Ok(UniqueKeysValue(Value::Null))
            }

            fn visit_some<D: Deserializer<'de>>(
                self,
                deserializer: D,
            ) -> Result<Self::Value, D::Error> {
                UniqueKeysValue::deserialize(deserializer)
            }

            fn visit_seq<A: de::SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
                let mut elements = Vec::new();
                while let Some(UniqueKeysValue(element)) = seq.next_element()? {
                    elements.push(element);
                }
                Ok(UniqueKeysValue(Value::Array(elements)))
            }

            fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
                let mut members = Map::new();
                while let Some((key, UniqueKeysValue(value))) =
                    map.next_entry::<String, UniqueKeysValue>()?
                {
                    if members.contains_key(&key) {
                        return Err(de::Error::custom(format!("duplicate key `{key}`")));
                    }
                    members.insert(key, value);
                }
                Ok(UniqueKeysValue(Value::Object(members)))
            }
        }

        deserializer.deserialize_any(ValueVisitor)
    }
}

/// Reads an optional property that, when present, must be a `T`.
///
/// Serde would read `null` as `None`, but the schema gives these properties a type such as
/// `string`, so `null` is wrong. This only runs when the property is there; with
/// `#[serde(default)]` a missing one is still `None`.
fn non_null<'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error>
where
    D: Deserializer<'de>,
    T: Deserialize<'de>,
{
    T::deserialize(deserializer).map(Some)
}

/// Reads a JSON object into a map and rejects a key that appears twice.
///
/// Serde's own map reader keeps the last value. Struct fields don't need this, because the
/// derive already rejects a repeated field.
fn unique_keys<'de, D, V>(deserializer: D) -> Result<BTreeMap<String, V>, D::Error>
where
    D: Deserializer<'de>,
    V: Deserialize<'de>,
{
    struct UniqueKeysVisitor<V>(PhantomData<V>);

    impl<'de, V: Deserialize<'de>> Visitor<'de> for UniqueKeysVisitor<V> {
        type Value = BTreeMap<String, V>;

        fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
            formatter.write_str("a JSON object")
        }

        fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
            let mut entries = BTreeMap::new();
            while let Some((key, value)) = map.next_entry::<String, V>()? {
                match entries.entry(key) {
                    Entry::Vacant(entry) => {
                        entry.insert(value);
                    }
                    Entry::Occupied(entry) => {
                        let key = entry.key();
                        return Err(de::Error::custom(format!("duplicate key `{key}`")));
                    }
                }
            }
            Ok(entries)
        }
    }

    deserializer.deserialize_map(UniqueKeysVisitor(PhantomData))
}

/// A project manifest couldn't be read.
///
/// The message names the manifest. The cause is in [`std::error::Error::source`] and isn't
/// repeated in the message.
#[derive(Debug, thiserror::Error)]
pub enum ReadManifestError {
    #[error("cannot read project manifest {}", path.display())]
    Io { path: PathBuf, source: io::Error },
    #[error("invalid project manifest {}", path.display())]
    Parse {
        path: PathBuf,
        source: serde_json::Error,
    },
}

/// Project metadata couldn't be read.
///
/// The message names the file. The cause is in [`std::error::Error::source`] and isn't repeated
/// in the message.
#[derive(Debug, thiserror::Error)]
pub enum ReadMetadataError {
    #[error("cannot read project metadata {}", path.display())]
    Io { path: PathBuf, source: io::Error },
    #[error("invalid project metadata {}", path.display())]
    Parse {
        path: PathBuf,
        source: serde_json::Error,
    },
}

/// Reads a project manifest.
///
/// A symbolic link, or anything else that isn't a regular file, is an I/O error. The same property
/// twice in one object is a parse error, which the derive takes care of.
pub fn read_manifest(path: &Path) -> Result<ProjectManifest, ReadManifestError> {
    let contents = read_regular_file(path).map_err(|source| ReadManifestError::Io {
        path: path.to_path_buf(),
        source,
    })?;
    serde_json::from_str(&contents).map_err(|source| ReadManifestError::Parse {
        path: path.to_path_buf(),
        source,
    })
}

/// Reads project metadata (`.meta.json`).
///
/// A symbolic link, or anything else that isn't a regular file, is an I/O error. A key that
/// appears twice in one object is a parse error.
pub fn read_metadata(path: &Path) -> Result<ProjectMetadata, ReadMetadataError> {
    let contents = read_regular_file(path).map_err(|source| ReadMetadataError::Io {
        path: path.to_path_buf(),
        source,
    })?;
    serde_json::from_str(&contents).map_err(|source| ReadMetadataError::Parse {
        path: path.to_path_buf(),
        source,
    })
}

/// Reads a file, refusing symbolic links, pipes and anything else that isn't a regular file.
///
/// The check and the read are separate steps. This guards against what's in a project, not
/// against another process swapping the file in between.
fn read_regular_file(path: &Path) -> io::Result<String> {
    if fs::symlink_metadata(path)?.file_type().is_file() {
        fs::read_to_string(path)
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "not a regular file",
        ))
    }
}
